// The Ira app's icons: one drawing, written out as SVG sources and rendered to
// the PNGs the web app manifest and iOS ask for.
//
//   node web/scripts/ira-icons.mjs            (Chrome at its macOS path, or CHROME=/path/to/chrome)
//
// The mark: five candles standing as a voice's level meter, short to tall to
// short, in the console's brand gradient (--brand-hi to --live) on the
// console's own ground (--bg0). The OpenFNO mark is dark candles on that
// gradient; Ira is the same candles turned to a voice, so the two sit side by
// side on a home screen as one family and are still told apart at a glance.
//
// Outputs (web/public/brand/):
//   ira-mark.svg               the source, rounded: the /ira tab's icon
//   ira-maskable.svg           the source, full bleed with the glyph inside the safe circle
//   ira-192.png, ira-512.png   "any": rounded tile, transparent corners
//   ira-maskable-512.png       "maskable": full bleed, for Android's own mask
//   ira-apple-touch-icon.png   180 px full bleed: iOS rounds it itself, and fills transparency with black
//
// Rendering is Chrome's own (headless --screenshot of each SVG), so the PNGs
// are exactly what a browser draws from the sources. Nothing is fetched.

import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const out = fileURLToPath(new URL('../public/brand/', import.meta.url))
const chrome = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

// The design tokens (styles.css :root): the dark ground and the brand gradient's two ends.
const BG0 = '#070b11'
const SURFACE = '#0d131c'
const BRAND_HI = '#7096ff'
const LIVE = '#2bd4bd'

/** Five candles on a 64 grid: body heights short to tall to short, a wick above and below each. */
const BODIES = [12, 22, 32, 22, 12]
const BODY_W = 5.6
const GAP = 2.4
const WICK_W = 1.6
const WICK = 4.5

/** The glyph, centred on (32, 32), at `scale` of its 64-grid size. */
function glyph(scale) {
  const width = BODIES.length * BODY_W + (BODIES.length - 1) * GAP
  const left = 32 - width / 2
  const parts = []
  BODIES.forEach((h, i) => {
    const x = left + i * (BODY_W + GAP)
    const top = 32 - h / 2
    parts.push(`<rect x="${(x + (BODY_W - WICK_W) / 2).toFixed(2)}" y="${(top - WICK).toFixed(2)}" width="${WICK_W}" height="${(h + 2 * WICK).toFixed(2)}" rx="${WICK_W / 2}" opacity=".55"/>`)
    parts.push(`<rect x="${x.toFixed(2)}" y="${top.toFixed(2)}" width="${BODY_W}" height="${h}" rx="1.8"/>`)
  })
  const t = 32 - 32 * scale
  return `<g transform="translate(${t.toFixed(3)} ${t.toFixed(3)}) scale(${scale})" fill="url(#ira-fg)">${parts.join('')}</g>`
}

/**
 * The icon as SVG. `rounded`: a tile with the console's 22% corner and transparent corners ("any" icons, the tab).
 * Otherwise full bleed (maskable, iOS), with the glyph smaller so it sits inside the maskable safe circle (80%).
 */
function svg({ px, rounded }) {
  const scale = rounded ? 1.18 : 0.96
  const tile = rounded ? `<rect width="64" height="64" rx="14" fill="url(#ira-bg)"/>` : `<rect width="64" height="64" fill="url(#ira-bg)"/>`
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${px}" height="${px}">`,
    '<defs>',
    `<linearGradient id="ira-bg" x1="0" y1="0" x2="0" y2="64" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${SURFACE}"/><stop offset="1" stop-color="${BG0}"/></linearGradient>`,
    `<linearGradient id="ira-fg" x1="0" y1="10" x2="0" y2="54" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${BRAND_HI}"/><stop offset="1" stop-color="${LIVE}"/></linearGradient>`,
    '</defs>',
    tile,
    glyph(scale),
    '</svg>',
  ].join('')
}

const SOURCE_NOTE = '<!-- Ira: five candles as a voice. Generated by web/scripts/ira-icons.mjs; edit the script, not this file. -->\n'
writeFileSync(join(out, 'ira-mark.svg'), SOURCE_NOTE + svg({ px: 64, rounded: true }) + '\n')
writeFileSync(join(out, 'ira-maskable.svg'), SOURCE_NOTE + svg({ px: 64, rounded: false }) + '\n')

const renders = [
  { file: 'ira-192.png', px: 192, rounded: true },
  { file: 'ira-512.png', px: 512, rounded: true },
  { file: 'ira-maskable-512.png', px: 512, rounded: false },
  { file: 'ira-apple-touch-icon.png', px: 180, rounded: false },
]

const work = mkdtempSync(join(tmpdir(), 'ira-icons-'))
try {
  for (const r of renders) {
    const source = join(work, r.file.replace(/\.png$/, '.svg'))
    writeFileSync(source, svg(r))
    execFileSync(chrome, [
      '--headless=new',
      '--disable-gpu',
      '--hide-scrollbars',
      '--force-device-scale-factor=1',
      '--default-background-color=00000000',
      `--window-size=${r.px},${r.px}`,
      `--screenshot=${join(out, r.file)}`,
      `file://${source}`,
    ], { stdio: 'ignore' })
    console.log(`  ${r.file}  ${r.px}×${r.px}`)
  }
} finally {
  rmSync(work, { recursive: true, force: true })
}
