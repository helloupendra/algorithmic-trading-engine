#!/usr/bin/env bash
# Moves the platform's data from one machine to another, in two halves:
#
#   ./scripts/aws/migrate-db.sh dump
#       -> algotrading-<date>.tar in the current directory:
#          the database (everything except raw ticks) and the ASP.NET data
#          protection keys that the stored broker credentials, trading PIN and
#          FYERS tokens are encrypted with. Without the keys the target could
#          not read them and you would re-enter the FYERS app credentials.
#
#   ./scripts/aws/migrate-db.sh restore <file.tar> [--wipe algotrading]
#       -> starts the API once so the migrations create the schema, empties
#          every table but the raw ticks, loads the dump, installs the keys.
#
# restore REPLACES the database. On one that holds any row it refuses, before it
# stops anything, unless --wipe is given with the database's name. A fresh server
# has no rows, so the first restore needs no flag. When a load fails it exits
# non-zero and never says "done": the tables have been emptied by then, so the
# desk must not be started on what is left. Fix the cause and run it again.
#
# Hypertables. TimescaleDB keeps a hypertable's rows in chunk tables in the
# _timescaledb_internal schema, and the table in public stays empty, so
# `pg_dump --schema=public` carries none of them: option_history_bars, mf_nav,
# mf_benchmark_tri and mf_ter would arrive empty. Each one is copied through a
# query instead (COPY (SELECT ...) TO STDOUT), which reads through the chunks and
# through compression, and loaded with COPY, which routes rows into the target's
# own chunks. The schema still comes from the migrations and the chunk layout
# from the target.
#
# How far this has been checked:
#   - from TimescaleDB's logical backup docs, not run here: pg_dump's table and
#     schema flags leave out what a hypertable needs, and the documented way to
#     move one is COPY (SELECT * FROM it);
#   - run, read-only, on a local TimescaleDB 2.27 / PostgreSQL 15: the guard's
#     query, the hypertable and column lists, a COPY out of an empty hypertable,
#     and pg_restore -l on a dump, which shows no data entry for a table left out
#     with --exclude-table-data;
#   - run against a stubbed docker: the script's logic (scripts/tests/migrate-db.test.sh);
#   - NOT run: a restore into a real database, or a dump of a hypertable with
#     rows (the local ones are empty). So on the first real move, read the
#     per-table counts the restore prints against the source before relying on it.
#
# Raw ticks (live_ticks, market_ticks: rolling days, GBs) are NOT carried over:
# they are regenerated by the next session and the console reads bars, candles,
# chains, runs and positions, all of which are included. Now that the option bars
# travel the dump can be far larger than it was: run it with room on the disk, on
# a quiet desk.
#
# Both halves talk to the database through the algotrading_db container, so
# no PostgreSQL client is needed on either machine.

set -euo pipefail
# REPO_ROOT may be given when the script runs from outside the checkout (the
# first restore happens before the server's checkout carries this file).
cd "${REPO_ROOT:-$(dirname "$0")/../..}"
REPO_ROOT="$PWD"
KEYS_DIR="$HOME/.aspnet/DataProtection-Keys"
DB_NAME=algotrading
RAW_TICKS="'live_ticks','market_ticks'"

db() { docker exec -i algotrading_db "$@"; }
sql() { db psql -U postgres -d "$DB_NAME" -v ON_ERROR_STOP=1 -Atc "$1"; }
say() { printf '%s  %s\n' "$(date '+%H:%M:%S')" "$1"; }

# The hypertables whose rows travel: every one in public but the raw ticks.
hypertables() {
  sql "select hypertable_name from timescaledb_information.hypertables where hypertable_schema='public' and hypertable_name not in ($RAW_TICKS) order by 1"
}

# A hypertable's columns, in order and quoted, for COPY. Named, so a column in a
# different place on the target still takes the right values, and a missing one
# fails instead of loading wrongly. A generated column cannot be loaded.
hypertable_columns() {
  sql "select string_agg(quote_ident(column_name), ', ' order by ordinal_position) from information_schema.columns where table_schema='public' and table_name='$1' and is_generated='NEVER'"
}

dump() {
  local stamp; stamp="$(date '+%Y%m%d-%H%M')"
  local work; work="$(mktemp -d)"
  # Asked for first, as an assignment: set -e does not see a failure inside a
  # `for` list, and the rows would be left out without a word.
  local tables table columns rows
  tables="$(hypertables)"

  # A hypertable's own (empty) table is left out of pg_dump's data too, so the
  # restore's pg_restore has nothing to do on one.
  local -a skip_data=(--exclude-table-data=live_ticks --exclude-table-data=market_ticks)
  for table in $tables; do skip_data+=("--exclude-table-data=$table"); done
  say "dumping the database (public schema, data only, without raw ticks) ..."
  db pg_dump -U postgres -d "$DB_NAME" --data-only --format=custom --schema=public \
      "${skip_data[@]}" --exclude-table='"__EFMigrationsHistory"' > "$work/algotrading.dump"
  say "  $(du -h "$work/algotrading.dump" | cut -f1)"

  mkdir "$work/hypertables"
  for table in $tables; do
    columns="$(hypertable_columns "$table")"
    printf '%s\n' "$columns" >"$work/hypertables/$table.columns"
    db psql -U postgres -d "$DB_NAME" -v ON_ERROR_STOP=1 -c "COPY (SELECT $columns FROM public.\"$table\") TO STDOUT" \
      | gzip -1 >"$work/hypertables/$table.copy.gz"
    # COPY's text format is one line a row, so this is the number that left.
    rows="$(gzip -dc "$work/hypertables/$table.copy.gz" | wc -l | tr -d ' ')"
    printf '%s\n' "$rows" >"$work/hypertables/$table.rows"
    say "  hypertable $table: $rows row(s), $(du -h "$work/hypertables/$table.copy.gz" | cut -f1)"
  done

  if [ -d "$KEYS_DIR" ]; then
    mkdir -p "$work/DataProtection-Keys" && cp "$KEYS_DIR"/*.xml "$work/DataProtection-Keys/" 2>/dev/null || true
    say "  data protection keys: $(ls "$work/DataProtection-Keys" | wc -l | tr -d ' ') file(s)"
  else
    say "  WARNING: no data protection keys at $KEYS_DIR — broker credentials will have to be re-entered on the target"
  fi
  local out="$REPO_ROOT/algotrading-$stamp.tar"
  tar -cf "$out" -C "$work" .
  rm -rf "$work"
  say "wrote $out ($(du -h "$out" | cut -f1)). Copy it to the target: scp -i key.pem $(basename "$out") ubuntu@<ip>:~/"
}

# One line per table that holds any row: "name  rows", capped at 1001 so a large
# table costs no full count. Every public table, seeded ones and raw ticks too: a
# guard that had to know which rows are seed would rot with each new table, and
# this can only refuse too much, which --wipe answers.
tables_with_rows() {
  sql "select table_name || '  ' || n from (select table_name, (xpath('/row/n/text()', query_to_xml(format('select count(*) as n from (select 1 from %I limit 1001) s', table_name), false, true, '')))[1]::text::bigint as n from information_schema.tables where table_schema='public' and table_type='BASE TABLE' and table_name <> '__EFMigrationsHistory') t where n > 0 order by table_name"
}

restore_failed() {
  printf '\nRESTORE FAILED: %s\n' "$1" >&2
  printf 'The tables were emptied before the load, so this database is NOT a good copy. Do not start the desk on it.\n' >&2
  printf 'Fix the cause and run the restore again: %s restore <file.tar> --wipe %s\n' "$0" "$DB_NAME" >&2
  exit 1
}

restore() {
  local tarfile="${1:-}" wipe_name=""
  [ -f "$tarfile" ] || { echo "usage: $0 restore <algotrading-*.tar> [--wipe $DB_NAME]" >&2; exit 2; }
  shift
  while [ $# -gt 0 ]; do
    case "$1" in
      --wipe)
        wipe_name="${2:-}"
        [ -n "$wipe_name" ] || { echo "--wipe needs the database's name: --wipe $DB_NAME" >&2; exit 2; }
        shift 2 ;;
      *) echo "unknown argument: $1" >&2; echo "usage: $0 restore <algotrading-*.tar> [--wipe $DB_NAME]" >&2; exit 2 ;;
    esac
  done
  . scripts/lib/desk-common.sh
  local work; work="$(mktemp -d)"
  # shellcheck disable=SC2064  # the path is known now, and this runs after the function's locals are gone
  trap "rm -rf '$work'" EXIT
  tar -xf "$tarfile" -C "$work"
  [ -f "$work/algotrading.dump" ] || { echo "no algotrading.dump inside $tarfile" >&2; exit 1; }

  # All of this before anything is stopped: a refused restore leaves a live desk
  # as it found it.
  if [ -n "$wipe_name" ] && [ "$wipe_name" != "$DB_NAME" ]; then
    printf 'REFUSED: --wipe names %s, but this restores into %s. Nothing was stopped or changed.\n' "$wipe_name" "$DB_NAME" >&2
    exit 3
  fi
  if ! db pg_isready -U postgres -q 2>/dev/null; then
    say "starting the database to see what it holds ..."; ( docker compose up -d --wait timescaledb >/dev/null )
  fi
  local holding
  holding="$(tables_with_rows)" || {
    printf 'REFUSED: could not read what %s holds (above). Nothing was stopped or changed.\n' "$DB_NAME" >&2
    exit 3
  }
  if [ -n "$holding" ] && [ -z "$wipe_name" ]; then
    {
      printf 'REFUSED: restore empties every table, and the database %s on this machine holds data:\n\n' "$DB_NAME"
      printf '%s\n' "$holding" | sed 's/^/  /'
      printf '\nNothing was stopped or changed. To keep these rows, first run: %s dump\n' "$0"
      printf 'To replace them: %s restore %s --wipe %s\n' "$0" "$tarfile" "$DB_NAME"
    } >&2
    exit 3
  fi
  if [ -n "$holding" ]; then
    say "--wipe $DB_NAME given: these tables are about to be emptied (counts stop at 1001):"
    printf '%s\n' "$holding" | sed 's/^/    /'
  fi

  say "stopping the desk and the API (if running) ..."
  sudo systemctl stop algotrading-desk 2>/dev/null || true
  api_stop
  say "infra up ..."; ( docker compose up -d --wait timescaledb redis >/dev/null )

  # The schema comes from the migrations, never from the dump: start the API
  # once, let it migrate and seed, then stop it. That is also what proves the
  # build runs on this machine before any data is involved.
  say "starting the API once to create the schema ..."
  api_start || { echo "the API did not start — fix that first (logs/api.log)" >&2; exit 1; }
  api_stop

  say "emptying the tables (the dump carries the real rows) ..."
  local tables
  tables="$(sql "select string_agg(format('%I', table_name), ', ') from information_schema.tables where table_schema='public' and table_type='BASE TABLE' and table_name not in ('__EFMigrationsHistory',$RAW_TICKS)")"
  db psql -U postgres -d "$DB_NAME" -v ON_ERROR_STOP=1 -qc "TRUNCATE $tables RESTART IDENTITY CASCADE"

  # Any error fails the restore. pg_restore reports them all and carries on, so
  # one run shows every one. The raw ticks' data is not in the dump
  # (--exclude-table-data leaves no data entry for them), so none can be theirs.
  say "loading the dump ..."
  db pg_restore -U postgres -d "$DB_NAME" --data-only --disable-triggers --no-owner < "$work/algotrading.dump" \
    || restore_failed "pg_restore reported errors (above)."

  local file table columns want answer got
  if [ -d "$work/hypertables" ]; then
    for file in "$work"/hypertables/*.copy.gz; do
      [ -f "$file" ] || continue
      table="$(basename "$file" .copy.gz)"
      columns="$(cat "$work/hypertables/$table.columns")"
      want="$(cat "$work/hypertables/$table.rows")"
      answer="$(gzip -dc "$file" | db psql -U postgres -d "$DB_NAME" -v ON_ERROR_STOP=1 -c "COPY public.\"$table\" ($columns) FROM STDIN")" \
        || restore_failed "could not load the hypertable $table (above)."
      got="${answer##COPY }"
      [ "$got" = "$want" ] || restore_failed "the hypertable $table took '$got' row(s) of the dump's $want."
      say "  hypertable $table: $got row(s), as many as the dump holds"
    done
  else
    say "  WARNING: this dump has no hypertables folder: it was made before they were carried, so their rows are NOT in it"
  fi
  say "  rows: users $(sql 'select count(*) from app_user'), runs $(sql 'select count(*) from simulation_runs'), candles $(sql 'select count(*) from candles'), chain rows $(sql 'select count(*) from option_chain_snapshots')"

  if [ -d "$work/DataProtection-Keys" ]; then
    mkdir -p "$KEYS_DIR"; cp "$work/DataProtection-Keys"/*.xml "$KEYS_DIR"/; chmod 600 "$KEYS_DIR"/*.xml
    say "data protection keys installed at $KEYS_DIR"
  fi
  say "done. Start the desk:  sudo systemctl start algotrading-desk   then  ./scripts/status.sh"
}

case "${1:-}" in
  dump) dump;;
  restore) shift; restore "$@";;
  *) echo "usage: $0 dump | restore <file.tar> [--wipe $DB_NAME]" >&2; exit 2;;
esac
