#!/usr/bin/env python3
"""
Generate the git-ignored `appsettings.Local.json` files from the repo-root `.env`.

Shared by scripts/setup.sh and scripts/setup.ps1 so the mapping from .env keys
to .NET configuration keys is defined exactly once, and so JSON/connection-string
escaping is handled correctly on every platform.

Usage:  python3 scripts/_gen_local_settings.py [--quiet]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = REPO_ROOT / ".env"

API_SETTINGS = REPO_ROOT / "src" / "AlgoTrading.Api" / "appsettings.Local.json"
WORKER_SETTINGS = (
    REPO_ROOT / "src" / "AlgoTrading.Worker.MarketData" / "appsettings.Local.json"
)

BANNER = (
    "GENERATED by scripts/setup.sh|ps1 from the repo-root .env. "
    "Do not edit by hand and do not commit — edit .env and re-run setup instead."
)


def read_env(path: Path) -> dict[str, str]:
    """Parse a dotenv file. Ignores comments/blank lines, strips paired quotes."""
    values: dict[str, str] = {}
    if not path.is_file():
        return values

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        values[key] = value
    return values


def npgsql_value(value: str) -> str:
    """Quote a connection-string value the way Npgsql expects.

    Npgsql splits on ';' and '=', so a password containing either — or leading /
    trailing whitespace — must be wrapped in double quotes with inner quotes
    doubled. Without this, a perfectly valid password silently produces a
    malformed connection string.
    """
    if value == "":
        return value
    needs_quoting = (
        any(ch in value for ch in ';="\'') or value != value.strip()
    )
    if not needs_quoting:
        return value
    return '"' + value.replace('"', '""') + '"'


def build_connection_string(env: dict[str, str]) -> str:
    parts = [
        f"Host={env.get('POSTGRES_HOST', 'localhost')}",
        f"Port={env.get('POSTGRES_PORT', '5432')}",
        f"Database={npgsql_value(env.get('POSTGRES_DB', 'algotrading'))}",
        f"Username={npgsql_value(env.get('POSTGRES_USER', 'postgres'))}",
        f"Password={npgsql_value(env.get('POSTGRES_PASSWORD', ''))}",
    ]
    return ";".join(parts)


def build_redis_connection(env: dict[str, str]) -> str:
    host = env.get("REDIS_HOST", "localhost")
    port = env.get("REDIS_PORT", "6379")
    conn = f"{host}:{port}"
    password = env.get("REDIS_PASSWORD", "")
    if password:
        conn += f",password={password}"
    return conn


def as_int(env: dict[str, str], key: str, default: int) -> int:
    try:
        return int(env[key])
    except (KeyError, ValueError):
        return default


def as_float(env: dict[str, str], key: str, default: float) -> float:
    try:
        return float(env[key])
    except (KeyError, ValueError):
        return default


def split_csv(value: str) -> list[str]:
    """Split a comma-separated setting into a clean list, dropping empties."""
    return [part.strip() for part in value.split(",") if part.strip()]


def only_set(pairs: dict[str, str]) -> dict[str, str]:
    """The pairs whose value is not empty.

    For sections whose C# registration falls back to the environment when a
    key is absent: an empty "ClientId": "" is not absent, so it would hide the
    DHAN_CLIENT_ID the API was started with.
    """
    return {key: value for key, value in pairs.items() if value}


def build_dhan_settings(env: dict[str, str]) -> dict:
    """The Dhan section, with only the values .env sets.

    Every deploy regenerates this file, and until 27 Sep it had no Dhan section:
    an API the desk restarted had no Dhan client id, so /api/Dhan/session was a
    404 and Connect could not work (24 Sep, 22 Sep). AccessToken is never
    written. The daily sign-in owns the token, and a pasted one outlives its
    day in .env: the feed ran on a dead one 238 times on 16 Sep.
    """
    dhan: dict = only_set({
        "ClientId": env.get("DHAN_CLIENT_ID", ""),
        "ApiKey": env.get("DHAN_API_KEY", ""),
        "ApiSecret": env.get("DHAN_API_SECRET", ""),
        # The automatic PIN + TOTP sign-in. Server only: two hosts holding
        # these would each take the account's token on their own schedule.
        "Pin": env.get("DHAN_PIN", ""),
        "TotpSecret": env.get("DHAN_TOTP_SECRET", ""),
    })
    poller = env.get("DHAN_CHAIN_POLLER_ENABLED", "").strip().lower()
    if poller in ("true", "false"):
        dhan["ChainPoller"] = {"Enabled": poller == "true"}
    return dhan


def build_portfolio_settings(env: dict[str, str]) -> dict:
    """The Portfolio page's own apps at the brokers, with only the values .env sets.

    Platform users sign in to these apps to link their own accounts, read only
    (docs/modules/portfolio.md). Left empty, the page uses the platform's FYERS
    app and Angel API key; FYERS lets only its creator sign in to an individual
    app. No user's credential is ever here: their tokens are encrypted in the
    database.
    """
    portfolio: dict = {}
    fyers = only_set({
        "AppId": env.get("PORTFOLIO_FYERS_APP_ID", ""),
        "SecretKey": env.get("PORTFOLIO_FYERS_SECRET_KEY", ""),
        "RedirectUri": env.get("PORTFOLIO_FYERS_REDIRECT_URI", ""),
    })
    if fyers:
        portfolio["Fyers"] = fyers
    angel = only_set({"ApiKey": env.get("PORTFOLIO_ANGEL_API_KEY", "")})
    if angel:
        portfolio["Angel"] = angel
    return portfolio


def build_api_settings(env: dict[str, str]) -> dict:
    """appsettings.Local.json for the API, from the parsed .env."""
    connection_string = build_connection_string(env)
    return {
        "//": BANNER,
        "ConnectionStrings": {"TradingDb": connection_string},
        "Jwt": {
            "Issuer": env.get("JWT_ISSUER", "AlgoTrading.Api"),
            "Audience": env.get("JWT_AUDIENCE", "AlgoTrading.App"),
            "SecretKey": env.get("JWT_SECRET_KEY", ""),
            "AccessTokenMinutes": as_int(env, "JWT_ACCESS_TOKEN_MINUTES", 60),
            "RefreshTokenDays": as_int(env, "JWT_REFRESH_TOKEN_DAYS", 7),
        },
        "Fyers": {
            "ClientId": env.get("FYERS_APP_ID", ""),
            "SecretKey": env.get("FYERS_SECRET_KEY", ""),
            "RedirectUri": env.get(
                "FYERS_REDIRECT_URI", "http://127.0.0.1:5025/api/auth/callback"
            ),
            "DataApiBaseUrl": env.get(
                "FYERS_DATA_API_BASE_URL", "https://api-t1.fyers.in"
            ),
        },
        "RiskManagement": {
            "MaxOrdersPerMinute": as_int(env, "RISK_MAX_ORDERS_PER_MINUTE", 50),
            "MaxDailyLoss": as_float(env, "RISK_MAX_DAILY_LOSS", -50000.0),
        },
        "Bootstrap": {
            "AdminUserName": env.get("ADMIN_USERNAME", "admin"),
            "AdminEmail": env.get("ADMIN_EMAIL", "admin@localhost"),
            # Empty means "generate one and print it once" — see AdminBootstrapper.
            "AdminPassword": env.get("ADMIN_PASSWORD", ""),
            # The Python engine signs in as this account to reach the API.
            "ServiceUserName": env.get("ENGINE_SERVICE_USERNAME", "engine-service"),
            "ServicePassword": env.get("ENGINE_SERVICE_PASSWORD", ""),
        },
        "Cors": {
            "AllowedOrigins": split_csv(
                env.get("CORS_ALLOWED_ORIGINS", "http://localhost:5173,http://localhost:3000")
            ),
        },
        "Telegram": {
            "BotToken": env.get("TELEGRAM_BOT_TOKEN", ""),
            "ChatId": env.get("TELEGRAM_CHAT_ID", ""),
            # The desk's own notices (feeds, sign-ins, deploys); the trades
            # chat above when empty. Candle patterns go to the trades chat
            # since 28 Sep unless PatternAlerts:TelegramChannel says system.
            "SystemChatId": env.get("TELEGRAM_SYSTEM_CHAT_ID", ""),
        },
        # Angel One SmartAPI. Four values, because its session is client code +
        # PIN + a TOTP code rather than a browser sign-in; the console cannot
        # hold them yet, so .env is where they live.
        "Angel": {
            "ApiKey": env.get("ANGEL_API_KEY", ""),
            "ClientCode": env.get("ANGEL_CLIENT_CODE", ""),
            "Pin": env.get("ANGEL_PIN", ""),
            "TotpSecret": env.get("ANGEL_TOTP_SECRET", ""),
            "RootUrl": env.get("ANGEL_ROOT_URL", "https://apiconnect.angelone.in"),
            # Shown in the console when a call is refused: the app answers only
            # from the IP it was registered with.
            "StaticIp": env.get("ANGEL_STATIC_IP", ""),
        },
        # The simulated broker. AdminKey is the whole broker's back office —
        # it opens traders' accounts and moves their money — so it lives in
        # .env like every other secret and is never returned by an endpoint.
        # The four account values below are only for a single account
        # configured by hand; traders' accounts are issued from the console.
        "SimBroker": {
            "BaseUrl": env.get("SIMBROKER_BASE_URL", "https://broker.openfno.com"),
            "AdminKey": env.get("SIMBROKER_ADMIN_KEY", ""),
            "ClientId": env.get("SIMBROKER_CLIENT_ID", ""),
            "AppId": env.get("SIMBROKER_APP_ID", ""),
            "AppSecret": env.get("SIMBROKER_APP_SECRET", ""),
            "TotpSecret": env.get("SIMBROKER_TOTP_SECRET", ""),
            "StaticIp": env.get("SIMBROKER_STATIC_IP", ""),
        },
        "Dhan": build_dhan_settings(env),
        "Portfolio": build_portfolio_settings(env),
        # NVIDIA's hosted models for the AI workspace (admin-only: the free
        # tier's terms cover development and evaluation, not serving users).
        # The key is used by the API alone and never returned by an endpoint.
        "Ai": {
            "ApiKey": env.get("NVIDIA_API_KEY", ""),
            "BaseUrl": env.get("NVIDIA_API_BASE_URL", "https://integrate.api.nvidia.com/v1"),
            **build_bedrock_settings(env),
            **build_bedrock_open_settings(env),
            **build_voice_settings(env),
            **build_actions_settings(env),
        },
    }


def build_bedrock_settings(env: dict[str, str]) -> dict:
    """Claude and Titan on Amazon Bedrock: only the switch and the region.

    No AWS credential is ever read from .env or written here: the API signs
    with the machine's default AWS chain (the EC2 instance profile). Unset
    values are left out, so the code's defaults (off, us-east-1) apply.
    """
    bedrock: dict = {}
    if env.get("AI_BEDROCK_ENABLED", "").strip().lower() == "true":
        bedrock["Enabled"] = True
    region = env.get("AI_BEDROCK_REGION", "").strip()
    if region:
        bedrock["Region"] = region
    return {"Bedrock": bedrock} if bedrock else {}


def build_bedrock_open_settings(env: dict[str, str]) -> dict:
    """The open models on Amazon Bedrock: only the switch (the region is AI_BEDROCK_REGION's).

    On in code, so the switch is written for true and for false, and left out
    otherwise. As for Claude, no AWS credential is ever read or written here.
    """
    switch = env.get("AI_BEDROCK_OPEN_ENABLED", "").strip().lower()
    return {"BedrockOpen": {"Enabled": switch == "true"}} if switch in ("true", "false") else {}


def build_voice_settings(env: dict[str, str]) -> dict:
    """Voice notes to the Telegram assistant and its spoken replies: the two switches and the speech-to-text.

    Both switches are on in code, so each is written for true and for false,
    and left out otherwise. The speech-to-text is Amazon Transcribe in code;
    AI_VOICE_TRANSCRIBE_PROVIDER=voxtral puts Voxtral on Bedrock back, and
    anything but the two names is left out. Transcription and Polly sign with
    the machine's AWS role: no AWS credential is ever read or written here.
    """
    voice: dict = {}
    for key, name in (("AI_VOICE_ENABLED", "Enabled"), ("AI_VOICE_SPEAK_REPLIES", "SpeakReplies")):
        switch = env.get(key, "").strip().lower()
        if switch in ("true", "false"):
            voice[name] = switch == "true"
    provider = env.get("AI_VOICE_TRANSCRIBE_PROVIDER", "").strip().lower()
    if provider in ("transcribe", "voxtral"):
        voice["TranscribeProvider"] = provider
    return {"Voice": voice} if voice else {}


def build_actions_settings(env: dict[str, str]) -> dict:
    """The Desk Assistant's PIN-confirmed actions: only the desk-wide switch.

    On in code, so the switch is written for true and for false, and left out
    otherwise. The owner's PIN is never in .env: only its hash, in the database.
    """
    switch = env.get("AI_ACTIONS_ENABLED", "").strip().lower()
    return {"Actions": {"Enabled": switch == "true"}} if switch in ("true", "false") else {}


def main() -> int:
    quiet = "--quiet" in sys.argv

    if not ENV_FILE.is_file():
        print(f"ERROR: {ENV_FILE} not found. Copy .env.example to .env first.",
              file=sys.stderr)
        return 1

    env = read_env(ENV_FILE)
    connection_string = build_connection_string(env)
    api_settings = build_api_settings(env)

    worker_settings = {
        "//": BANNER,
        "ConnectionStrings": {
            "TradingDb": connection_string,
            "DefaultConnection": connection_string,
        },
        "Redis": {
            "ConnectionString": build_redis_connection(env),
            "StreamName": env.get("REDIS_STREAM_NAME", "market:ticks"),
            "ConsumerGroup": "market-data-workers",
            "ConsumerName": "market-worker-1",
            "ReadBatchSize": 200,
            "PollDelayMs": 500,
        },
    }

    for path, payload in ((API_SETTINGS, api_settings),
                          (WORKER_SETTINGS, worker_settings)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        # Owner-only: the file holds the database password, the JWT key and
        # every broker secret. Written with the default umask it was 0644 —
        # readable by any account on the server (Sentinel's first scan, 27 Sep).
        path.chmod(0o600)
        if not quiet:
            print(f"  wrote {path.relative_to(REPO_ROOT)}")

    missing = [
        key
        for key in ("POSTGRES_PASSWORD", "FYERS_APP_ID", "FYERS_SECRET_KEY",
                    "JWT_SECRET_KEY")
        if not env.get(key) or env[key].startswith(("YOUR_", "REPLACE_", "change-me"))
    ]
    if missing and not quiet:
        print(
            "\n  NOTE: these .env values are still placeholders -> "
            + ", ".join(missing)
        )
        print("        Infrastructure will start, but broker login will fail "
              "until they are set.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
